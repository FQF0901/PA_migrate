typedef struct
{
    IfxDma_Dma                dmaHandle;                         /* Module handle to HW module SFR set              */
    IfxDma_Dma_Config         dmaConfig;                         /* Module configuration structure                  */
    IfxDma_Dma_ChannelConfig  dmaChNCfg;                         /* DMA whole channel configurations                */
    IfxDma_Dma_Channel        dmaChannel;                        /* DMA channel configuration set                   */
    uint32                    successfulDmaTransaction;          /* Number of successful DMA transactions           */
    uint32                    failedDmaTransaction;              /* Number of failed DMA transactions               */
    void                     *pSourceAddressForDmaTransfer;      /* DMA data source address - reload value          */
    void                     *pDestinationAddressForDmaTransfer; /* DMA data destination address - reload v.        */
    uint32                    SourceAddr;
    uint32                    DestinationAddr;
} dmaParams;


typedef struct
{
    IfxGtm_Atom_Timer_Base base;   /**< \brief Timer base structure */
    Ifx_GTM* gtm;                  /**< \brief GTM module used for the timer functionality */
    Ifx_GTM_ATOM* atom;            /**< \brief ATOM used for the timer functionality */
    Ifx_GTM_ATOM_AGC* agc;         /**< \brief Pointer to the AGC object */
    IfxGtm_Atom atomIndex;         /**< \brief Enum for ATOM objects */
    IfxGtm_Atom_Ch timerChannel;   /**< \brief ATOM channel used for the timer */
    IfxGtm_Atom_Ch triggerChannel; /**< \brief ATOM channel used for the trigger, if identical to the timerChannel, the
                                      trigger interrupt is having the same interrupt level as  the timer interrupt */
    uint16 channelsMask;           /**< \brief Mask for channels to be modified together */
    Ifx_TimerValue offset;         /**< \brief Timer initial offset in ticks */
    uint32 agcDisableUpdate;       /**< \brief AGC value for disable update */
    uint32 agcApplyUpdate;         /**< \brief AGC value for apply update */
    boolean enable;
} EMGtm_Atom_Driver;

/** \brief Configuration structure for ATOM Driver
 */
typedef struct
{
    IfxStdIf_Timer_Config base; /**< \brief Standard interface timer configuration */
    Ifx_GTM* gtm;               /**< \brief GTM used for the timer functionality */
    IfxGtm_Atom atom;           /**< \brief ATOM used for the timer functionality */
    IfxGtm_Atom_Ch Channel;     /**< \brief ATOM channel used for the timer */
    IfxGtm_Atom_ToutMap*
        triggerOut;       /**< \brief ATOM channel used for the trigger output, can be identical to the timer channe */
    IfxGtm_Cmu_Clk clock; /**< \brief Timer input clock */
    IfxGtm_IrqMode irqModeTimer;   /**< \brief Interrupt mode for the timer */
    IfxGtm_IrqMode irqModeTrigger; /**< \brief Interrupt mode for the trigger */
    Ifx_Priority isrPriority; /**< \brief Interrupt isrPriority of the timer interrupt, if 0 the interrupt is disable */
    IfxSrc_Tos isrProvider;   /**< \brief Interrupt service provider for the timer interrupt */

    boolean initPins; /**< \brief TRUE: Initialize pins in driver
                       * FALSE: Don't initialize pins in driver : user handles separately */
} EMGtm_Atom_Config;

